-- Создание схемы и таблиц
CREATE SCHEMA marketplace;
SET search_path TO marketplace;

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    name text NOT NULL CHECK (length(trim(name)) > 0),
    city text,
    created_at timestamptz NOT NULL,
    CHECK (email LIKE '%@%')
);

CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    parent_id bigint REFERENCES categories(id),
    CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id bigint NOT NULL REFERENCES categories(id),
    name text NOT NULL CHECK (length(trim(name)) > 0),
    price_kopecks bigint NOT NULL CHECK (price_kopecks > 0),
    stock integer NOT NULL CHECK (stock >= 0),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL
);

CREATE TABLE orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    status text NOT NULL CHECK (status IN ('new', 'paid', 'shipped', 'completed', 'canceled')),
    created_at timestamptz NOT NULL,
    canceled_at timestamptz,
    CHECK ((status = 'canceled') = (canceled_at IS NOT NULL)),
    CHECK (canceled_at IS NULL OR canceled_at >= created_at)
);

CREATE TABLE order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders(id),
    product_id bigint NOT NULL REFERENCES products(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price_kopecks bigint NOT NULL CHECK (unit_price_kopecks > 0),
    UNIQUE (order_id, product_id),
    UNIQUE (id, order_id)
);

CREATE TABLE payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders(id),
    status text NOT NULL CHECK (status IN ('pending', 'succeeded', 'failed')),
    amount_kopecks bigint NOT NULL CHECK (amount_kopecks > 0),
    method text NOT NULL CHECK (method IN ('card', 'bank_transfer')),
    created_at timestamptz NOT NULL,
    paid_at timestamptz,
    UNIQUE (id, order_id),
    CHECK ((status = 'succeeded') = (paid_at IS NOT NULL)),
    CHECK (paid_at IS NULL OR paid_at >= created_at)
);

CREATE TABLE refunds (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders(id),
    order_item_id bigint NOT NULL,
    payment_id bigint NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    amount_kopecks bigint NOT NULL CHECK (amount_kopecks > 0),
    status text NOT NULL CHECK (status IN ('requested', 'completed', 'rejected')),
    reason text,
    created_at timestamptz NOT NULL,
    FOREIGN KEY (order_item_id, order_id) REFERENCES order_items(id, order_id),
    FOREIGN KEY (payment_id, order_id) REFERENCES payments(id, order_id)
);

CREATE TABLE reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    product_id bigint NOT NULL REFERENCES products(id),
    rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    body text,
    created_at timestamptz NOT NULL,
    UNIQUE (user_id, product_id)
);

CREATE TABLE carts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES users(id),
    updated_at timestamptz NOT NULL
);

CREATE TABLE cart_items (
    cart_id bigint NOT NULL REFERENCES carts(id),
    product_id bigint NOT NULL REFERENCES products(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (cart_id, product_id)
);

COMMENT ON COLUMN order_items.unit_price_kopecks IS 'Цена на момент заказа, не текущая цена товара';
COMMENT ON TABLE refunds IS 'Возврат позиции; только completed уменьшает денежную выручку';
COMMENT ON TABLE payments IS 'Попытки оплаты: failed и pending не являются полученными деньгами';

